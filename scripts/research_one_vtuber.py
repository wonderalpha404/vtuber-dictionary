def validate_result(data, uuid, name):
    if not isinstance(data, dict):
        raise ValueError("AI response is not a JSON object")

    required_fields = {
        "uuid",
        "name",
        "reading",
        "source",
        "source_type",
        "confidence",
        "status",
        "notes",
    }

    missing = required_fields - set(data.keys())

    if missing:
        raise ValueError(
            f"AI JSON missing required fields: {sorted(missing)}"
        )

    if data["uuid"] != uuid:
        raise ValueError(
            f"UUID mismatch: expected={uuid!r} actual={data['uuid']!r}"
        )

    if data["name"] != name:
        raise ValueError(
            f"name mismatch: expected={name!r} actual={data['name']!r}"
        )

    if not isinstance(data["reading"], str):
        raise ValueError("reading must be a string")

    if not isinstance(data["source"], str):
        raise ValueError("source must be a string")

    if not isinstance(data["source_type"], str):
        raise ValueError("source_type must be a string")

    if not isinstance(data["confidence"], str):
        raise ValueError("confidence must be a string")

    if not isinstance(data["status"], str):
        raise ValueError("status must be a string")

    if not isinstance(data["notes"], str):
        raise ValueError("notes must be a string")

    if data["status"] not in ALLOWED_STATUS:
        raise ValueError(
            f"Invalid status: {data['status']!r}"
        )

    if data["confidence"] not in ALLOWED_CONFIDENCE:
        raise ValueError(
            f"Invalid confidence: {data['confidence']!r}"
        )

    if data["source_type"] not in ALLOWED_SOURCE_TYPES:
        raise ValueError(
            f"Invalid source_type: {data['source_type']!r}"
        )

    if data["reading"] and not data["source"]:
        raise ValueError(
            "AI returned a reading without a supporting source"
        )

    return data


def request_openrouter_once(uuid, name, prompt, attempt):
    api_key = os.environ.get("OPENROUTER_API_KEY")

    if not api_key:
        raise RuntimeError("OPENROUTER_API_KEY is not set")

    payload = {
        "model": OPENROUTER_MODEL,
        "messages": [
            {
                "role": "user",
                "content": prompt,
            }
        ],
        "response_format": {
            "type": "json_object"
        },
        "tools": [
            {
                "type": "openrouter:web_search"
            }
        ],
    }

    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "HTTP-Referer": "https://github.com/wonderalpha404/vtuber-dictionary",
        "X-Title": "VTuber Dictionary Reading Research",
    }

    log("OPENROUTER REQUEST")
    log(f"name={name}")
    log(f"uuid={uuid}")
    log(f"attempt={attempt}/{MAX_API_ATTEMPTS}")
    log(f"model={OPENROUTER_MODEL}")
    log("web_search=true")
    log(
        f"connect_timeout={CONNECT_TIMEOUT}s "
        f"read_timeout={READ_TIMEOUT}s"
    )
    log(f"max_attempts={MAX_API_ATTEMPTS}")

    started = time.monotonic()

    try:
        response = requests.post(
            OPENROUTER_URL,
            headers=headers,
            json=payload,
            timeout=(CONNECT_TIMEOUT, READ_TIMEOUT),
        )

    except requests.exceptions.ConnectTimeout as exc:
        elapsed = time.monotonic() - started

        log(
            f"OPENROUTER CONNECT TIMEOUT "
            f"name={name} uuid={uuid} "
            f"attempt={attempt}/{MAX_API_ATTEMPTS} "
            f"elapsed={elapsed:.1f}s"
        )

        raise RuntimeError(
            f"OpenRouter connection timeout after {elapsed:.1f}s"
        ) from exc

    except requests.exceptions.ReadTimeout as exc:
        elapsed = time.monotonic() - started

        log(
            f"OPENROUTER READ TIMEOUT "
            f"name={name} uuid={uuid} "
            f"attempt={attempt}/{MAX_API_ATTEMPTS} "
            f"elapsed={elapsed:.1f}s"
        )

        raise RuntimeError(
            f"OpenRouter read timeout after {elapsed:.1f}s"
        ) from exc

    except requests.exceptions.RequestException as exc:
        elapsed = time.monotonic() - started

        log(
            f"OPENROUTER REQUEST ERROR "
            f"name={name} uuid={uuid} "
            f"attempt={attempt}/{MAX_API_ATTEMPTS} "
            f"elapsed={elapsed:.1f}s"
        )

        raise RuntimeError(
            f"OpenRouter request error: {exc}"
        ) from exc

    elapsed = time.monotonic() - started

    log(
        f"OPENROUTER HTTP RESPONSE "
        f"name={name} uuid={uuid} "
        f"attempt={attempt}/{MAX_API_ATTEMPTS} "
        f"status={response.status_code} "
        f"elapsed={elapsed:.1f}s "
        f"bytes={len(response.content)}"
    )

    if response.status_code != 200:
        body_preview = response.text[:1000].replace("\n", "\\n")

        log(
            f"OPENROUTER HTTP ERROR BODY PREVIEW "
            f"name={name} uuid={uuid} "
            f"attempt={attempt}/{MAX_API_ATTEMPTS}: "
            f"{body_preview}"
        )

        raise RuntimeError(
            f"OpenRouter HTTP status {response.status_code}"
        )

    try:
        data = response.json()

    except json.JSONDecodeError as exc:
        body_preview = response.text[:1000].replace("\n", "\\n")

        log(
            f"OPENROUTER RESPONSE JSON PARSE FAILED "
            f"name={name} uuid={uuid} "
            f"attempt={attempt}/{MAX_API_ATTEMPTS}"
        )
        log(
            f"HTTP BODY PREVIEW: {body_preview}"
        )

        raise RuntimeError(
            f"Failed to parse OpenRouter HTTP response as JSON: {exc}"
        ) from exc

    log(
        f"OPENROUTER RESPONSE STRUCTURE "
        f"name={name} uuid={uuid} "
        f"attempt={attempt}/{MAX_API_ATTEMPTS} "
        f"top_level_keys={list(data.keys())}"
    )

    choices = data.get("choices")

    if not isinstance(choices, list) or not choices:
        raise RuntimeError(
            "OpenRouter response contains no choices"
        )

    log(
        f"OPENROUTER CHOICES "
        f"name={name} uuid={uuid} "
        f"attempt={attempt}/{MAX_API_ATTEMPTS} "
        f"count={len(choices)}"
    )

    message = choices[0].get("message")

    if not isinstance(message, dict):
        raise RuntimeError(
            "OpenRouter response contains no message object"
        )

    log(
        f"OPENROUTER MESSAGE FOUND "
        f"name={name} uuid={uuid} "
        f"attempt={attempt}/{MAX_API_ATTEMPTS} "
        f"message_keys={list(message.keys())}"
    )

    refusal = message.get("refusal")

    if refusal:
        log(
            f"OPENROUTER REFUSAL "
            f"name={name} uuid={uuid} "
            f"attempt={attempt}/{MAX_API_ATTEMPTS} "
            f"refusal={str(refusal)[:1000]}"
        )

        raise RuntimeError(
            "OpenRouter returned a refusal"
        )

    content = message.get("content")

    if not isinstance(content, str):
        raise RuntimeError(
            "OpenRouter message content is not a string"
        )

    log(
        f"OPENROUTER AI CONTENT RECEIVED "
        f"name={name} uuid={uuid} "
        f"attempt={attempt}/{MAX_API_ATTEMPTS} "
        f"content_length={len(content)}"
    )

    return content


def request_openrouter(uuid, name, prompt):
    last_error = None

    for attempt in range(1, MAX_API_ATTEMPTS + 1):
        try:
            return request_openrouter_once(
                uuid=uuid,
                name=name,
                prompt=prompt,
                attempt=attempt,
            )

        except Exception as exc:
            last_error = exc

            log(
                f"OPENROUTER ATTEMPT FAILED "
                f"name={name} uuid={uuid} "
                f"attempt={attempt}/{MAX_API_ATTEMPTS} "
                f"error_type={type(exc).__name__} "
                f"message={exc}"
            )

            if attempt >= MAX_API_ATTEMPTS:
                log(
                    f"OPENROUTER ALL ATTEMPTS FAILED "
                    f"name={name} uuid={uuid} "
                    f"attempts={MAX_API_ATTEMPTS}"
                )
                raise

            delay = RETRY_DELAYS[attempt - 1]

            log(
                f"OPENROUTER RETRY SCHEDULED "
                f"name={name} uuid={uuid} "
                f"next_attempt={attempt + 1}/{MAX_API_ATTEMPTS} "
                f"wait={delay}s"
            )

            time.sleep(delay)

    raise RuntimeError(
        f"OpenRouter failed after {MAX_API_ATTEMPTS} attempts: {last_error}"
    )


def research(uuid, name):
    started_at = utc_now()

    log("RESEARCH START")
    log(f"uuid={uuid}")
    log(f"RESEARCH TARGET name={name} uuid={uuid}")

    if is_kana_only_name(name):
        log(
            f"DETERMINISTIC KANA-ONLY "
            f"name={name} uuid={uuid} "
            f"ai_call=false "
            f"reason=kana-only"
        )

        try:
            result = make_deterministic_result(
                uuid=uuid,
                name=name,
            )
            upsert_result(result)

            log(
                f"RESULT SAVED "
                f"name={name} "
                f"uuid={uuid} "
                f"reading={result['reading']} "
                f"status={result['status']} "
                f"confidence={result['confidence']}"
            )

            log(
                f"RESEARCH SUCCESS "
                f"name={name} uuid={uuid} "
                f"method=deterministic"
            )

            return 0

        except Exception as exc:
            log(
                f"DETERMINISTIC PROCESSING FAILED "
                f"name={name} uuid={uuid} "
                f"error_type={type(exc).__name__} "
                f"message={exc}"
            )

            existing = None

            try:
                existing = get_existing_result(uuid)
            except Exception as load_exc:
                log(
                    f"EXISTING RESULT LOAD FAILED "
                    f"name={name} "
                    f"uuid={uuid} "
                    f"error_type={type(load_exc).__name__} "
                    f"message={load_exc}"
                )

            if (
                existing is not None
                and existing.get("status") in ALLOWED_STATUS
                and existing.get("last_attempt_result") == "success"
            ):
                log(
                    f"EXISTING SUCCESS RESULT NOT OVERWRITTEN "
                    f"name={name} "
                    f"uuid={uuid} "
                    f"status={existing.get('status')}"
                )

            else:
                failure = make_failure_record(
                    uuid=uuid,
                    name=name,
                    started_at=started_at,
                    existing=existing,
                )

                try:
                    upsert_result(failure)

                    log(
                        f"FAILURE STATE SAVED "
                        f"name={name} "
                        f"uuid={uuid} "
                        f"status=pending "
                        f"last_attempt_result=error"
                    )

                except Exception as save_exc:
                    log(
                        f"FAILURE STATE SAVE FAILED "
                        f"name={name} "
                        f"uuid={uuid} "
                        f"error_type={type(save_exc).__name__} "
                        f"message={save_exc}"
                    )

            log(
                f"RESEARCH FAILED "
                f"name={name} "
                f"uuid={uuid} "
                f"error_type={type(exc).__name__} "
                f"message={exc}"
            )

            return 1

    prompt = build_prompt(uuid, name)

    log(
        f"RESEARCH PROMPT READY "
        f"name={name} uuid={uuid} "
        f"prompt_length={len(prompt)}"
    )

    try:
        content = request_openrouter(
            uuid=uuid,
            name=name,
            prompt=prompt,
        )

        log(
            f"AI RESPONSE RECEIVED "
            f"name={name} "
            f"content_length={len(content)}"
        )

        try:
            data = extract_json_object(content)

        except ValueError as exc:
            log(
                f"AI RESPONSE PARSE FAILED "
                f"name={name} "
                f"error_type=invalid_json"
            )

            preview = content[:1000].replace("\n", "\\n")

            log(
                f"AI RESPONSE START PREVIEW: {preview}"
            )

            if len(content) > 1000:
                end_preview = content[-1000:].replace("\n", "\\n")

                log(
                    f"AI RESPONSE END PREVIEW: {end_preview}"
                )

            raise ValueError(
                "Failed to parse AI response as a JSON object"
            ) from exc

        log(
            f"AI JSON PARSED "
            f"name={name} uuid={uuid}"
        )

        data = validate_result(
            data=data,
            uuid=uuid,
            name=name,
        )

        finished_at = utc_now()

        result = {
            "uuid": data["uuid"],
            "name": data["name"],
            "reading": data["reading"],
            "source": data["source"],
            "source_type": data["source_type"],
            "confidence": data["confidence"],
            "status": data["status"],
            "notes": data["notes"],
            "checked_at": finished_at,
            "last_attempted_at": finished_at,
            "last_attempt_result": "success",
        }

        upsert_result(result)

        log(
            f"RESULT SAVED "
            f"name={name} "
            f"uuid={uuid} "
            f"reading={result['reading']} "
            f"status={result['status']} "
            f"confidence={result['confidence']}"
        )

        log(
            f"RESEARCH SUCCESS "
            f"name={name} uuid={uuid}"
        )

        return 0

    except Exception as exc:
        existing = None

        try:
            existing = get_existing_result(uuid)
        except Exception as load_exc:
            log(
                f"EXISTING RESULT LOAD FAILED "
                f"name={name} "
                f"uuid={uuid} "
                f"error_type={type(load_exc).__name__} "
                f"message={load_exc}"
            )

        if (
            existing is not None
            and existing.get("status") in ALLOWED_STATUS
            and existing.get("last_attempt_result") == "success"
        ):
            log(
                f"EXISTING SUCCESS RESULT NOT OVERWRITTEN "
                f"name={name} "
                f"uuid={uuid} "
                f"status={existing.get('status')}"
            )

        else:
            failure = make_failure_record(
                uuid=uuid,
                name=name,
                started_at=started_at,
                existing=existing,
            )

            try:
                upsert_result(failure)

                log(
                    f"FAILURE STATE SAVED "
                    f"name={name} "
                    f"uuid={uuid} "
                    f"status=pending "
                    f"last_attempt_result=error"
                )

            except Exception as save_exc:
                log(
                    f"FAILURE STATE SAVE FAILED "
                    f"name={name} "
                    f"uuid={uuid} "
                    f"error_type={type(save_exc).__name__} "
                    f"message={save_exc}"
                )

        log(
            f"RESEARCH FAILED "
            f"name={name} "
            f"uuid={uuid} "
            f"error_type={type(exc).__name__} "
            f"message={exc}"
        )

        return 1


def main():
    if len(sys.argv) != 3:
        print(
            "Usage: python scripts/research_one_vtuber.py <uuid> <name>",
            file=sys.stderr,
        )
        return 2

    uuid = sys.argv[1]
    name = sys.argv[2]

    return research(
        uuid=uuid,
        name=name,
    )


if __name__ == "__main__":
    sys.exit(main())
