#!/usr/bin/env python3

import json
import os
import re
import sys
import time
from datetime import datetime, timezone

import requests


OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"
OPENROUTER_MODEL = "openrouter/free"

CONNECT_TIMEOUT = 15
READ_TIMEOUT = 60

MAX_API_ATTEMPTS = 3
RETRY_DELAYS = [30, 60]

OUTPUT_FILE = "source/vtuber-readings.json"

ALLOWED_STATUS = {"verified", "review", "unknown"}
ALLOWED_CONFIDENCE = {"high", "medium", "review", "unknown"}
ALLOWED_SOURCE_TYPES = {
    "official",
    "wikipedia",
    "vtuber_database",
    "media",
    "other",
    "",
}


KANA_ONLY_RE = re.compile(r"^[\u3040-\u309f\u30a0-\u30ff・ー]+$")


def utc_now():
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace(
        "+00:00", "Z"
    )


def log(message):
    print(message, file=sys.stderr, flush=True)


def is_kana_only_name(name):
    return bool(name) and bool(KANA_ONLY_RE.fullmatch(name))


def kana_to_reading(name):
    reading_chars = []

    for char in name:
        codepoint = ord(char)

        if char == "・":
            continue

        if "\u30a1" <= char <= "\u30f6":
            char = chr(codepoint - 0x60)

        reading_chars.append(char)

    return "".join(reading_chars)


def make_deterministic_result(uuid, name):
    reading = kana_to_reading(name)

    if not reading:
        raise ValueError("Kana-only name produced an empty reading")

    checked_at = utc_now()

    return {
        "uuid": uuid,
        "name": name,
        "reading": reading,
        "source": "deterministic:kana-only",
        "source_type": "other",
        "confidence": "high",
        "status": "verified",
        "notes": "name.jp is kana-only; reading was generated by deterministic kana conversion. Middle dot was not read.",
        "checked_at": checked_at,
        "last_attempted_at": checked_at,
        "last_attempt_result": "success",
    }


def make_failure_record(uuid, name, started_at, existing=None):
    notes = ""

    if isinstance(existing, dict):
        notes = existing.get("notes", "")

    return {
        "uuid": uuid,
        "name": name,
        "reading": "",
        "source": "",
        "source_type": "",
        "confidence": "unknown",
        "status": "pending",
        "notes": notes,
        "checked_at": "",
        "last_attempted_at": started_at,
        "last_attempt_result": "error",
    }


def load_results():
    if not os.path.exists(OUTPUT_FILE):
        return []

    with open(OUTPUT_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, list):
        raise ValueError(f"{OUTPUT_FILE} must contain a JSON array")

    return data


def save_results(results):
    temp_file = OUTPUT_FILE + ".tmp"

    with open(temp_file, "w", encoding="utf-8") as f:
        json.dump(
            results,
            f,
            ensure_ascii=False,
            indent=2,
        )
        f.write("\n")

    os.replace(temp_file, OUTPUT_FILE)


def upsert_result(record):
    results = load_results()

    uuid = record["uuid"]

    for i, existing in enumerate(results):
        if existing.get("uuid") == uuid:
            results[i] = record
            save_results(results)
            return

    results.append(record)
    save_results(results)


def get_existing_result(uuid):
    results = load_results()

    for record in results:
        if record.get("uuid") == uuid:
            return record

    return None


def extract_json_object(text):
    """
    Extract a JSON object from the AI response.

    Accepts:
    - pure JSON
    - JSON inside a Markdown code fence
    - JSON surrounded by accidental prose

    Does NOT invent or repair missing JSON.
    """

    if not isinstance(text, str):
        raise ValueError("AI response content is not a string")

    text = text.strip()

    if not text:
        raise ValueError("AI response content is empty")

    try:
        parsed = json.loads(text)

        if isinstance(parsed, dict):
            return parsed

        raise ValueError("AI response JSON is not an object")

    except json.JSONDecodeError:
        pass

    fenced = re.search(
        r"```(?:json)?\s*(\{.*?\})\s*```",
        text,
        flags=re.DOTALL | re.IGNORECASE,
    )

    if fenced:
        candidate = fenced.group(1)

        try:
            parsed = json.loads(candidate)

            if isinstance(parsed, dict):
                return parsed

        except json.JSONDecodeError as exc:
            raise ValueError(
                f"JSON code fence found but JSON is invalid: {exc}"
            ) from exc

    start = text.find("{")

    if start >= 0:
        depth = 0
        in_string = False
        escaped = False

        for i in range(start, len(text)):
            char = text[i]

            if in_string:
                if escaped:
                    escaped = False
                elif char == "\\":
                    escaped = True
                elif char == '"':
                    in_string = False
                continue

            if char == '"':
                in_string = True
                continue

            if char == "{":
                depth += 1

            elif char == "}":
                depth -= 1

                if depth == 0:
                    candidate = text[start : i + 1]

                    try:
                        parsed = json.loads(candidate)

                        if isinstance(parsed, dict):
                            return parsed

                    except json.JSONDecodeError as exc:
                        raise ValueError(
                            f"Embedded JSON object is invalid: {exc}"
                        ) from exc

        raise ValueError("Could not find a complete valid JSON object")

    raise ValueError("No JSON object found in AI response")


